"""Makes the site installable and usable offline.

    python3 tools_build/make_pwa.py

Writes icons/ (once) and sw.js: a service worker that caches every file of the
site plus the Pyodide runtime. Run it before every commit: the file list and
version hash change whenever any site file changes, which makes phones update.
"""
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
PYODIDE = 'https://cdn.jsdelivr.net/pyodide/v0.26.4/full/'
PYODIDE_FILES = ['pyodide.js', 'pyodide.asm.js', 'pyodide.asm.wasm', 'python_stdlib.zip',
                 'pyodide-lock.json']
SKIP_DIRS = {'.git', 'tools_build', '.claude'}
SKIP_FILES = {'sw.js', 'README.md', '.gitignore', '.nojekyll'}


def make_icons():
    from PIL import Image, ImageDraw, ImageFont
    out = os.path.join(SITE, 'icons')
    os.makedirs(out, exist_ok=True)
    font_path = None
    for f in ('/System/Library/Fonts/Supplemental/Arial Bold.ttf',
              '/System/Library/Fonts/Helvetica.ttc', '/Library/Fonts/Arial Bold.ttf'):
        if os.path.exists(f):
            font_path = f
            break
    for name, size in (('icon-512.png', 512), ('icon-192.png', 192), ('apple-touch-icon.png', 180)):
        img = Image.new('RGB', (size, size), (15, 118, 110))
        d = ImageDraw.Draw(img)
        font = ImageFont.truetype(font_path, int(size * 0.42)) if font_path else ImageFont.load_default()
        text = 'TA'
        box = d.textbbox((0, 0), text, font=font)
        w, h = box[2] - box[0], box[3] - box[1]
        d.text(((size - w) / 2 - box[0], (size - h) / 2 - box[1]), text, font=font, fill=(255, 255, 255))
        img.save(os.path.join(out, name))


def site_files():
    files = []
    for root, dirs, names in os.walk(SITE):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith('.'))
        for n in sorted(names):
            rel = os.path.relpath(os.path.join(root, n), SITE).replace(os.sep, '/')
            if '/' not in rel and n in SKIP_FILES:
                continue
            if n.startswith('.') or n.endswith('.pyc'):
                continue
            files.append(rel)
    return files


def make_sw():
    files = site_files()
    h = hashlib.sha1()
    for f in files:
        with open(os.path.join(SITE, f), 'rb') as fh:
            h.update(f.encode() + fh.read())
    version = h.hexdigest()[:10]
    listing = ',\n  '.join("'./%s'" % f for f in ['.'] + files if f != '.')
    sw = SW_TEMPLATE.replace('__VERSION__', version).replace('__FILES__', "'./',\n  " + listing) \
        .replace('__PYODIDE__', ',\n  '.join("'%s%s'" % (PYODIDE, f) for f in PYODIDE_FILES))
    with open(os.path.join(SITE, 'sw.js'), 'w') as fh:
        fh.write(sw)
    print('sw.js: %d files, version %s' % (len(files), version))


SW_TEMPLATE = r"""// Generated by tools_build/make_pwa.py - do not edit by hand.
// Caches the whole site and the Pyodide runtime so it works offline.
var VERSION = '__VERSION__';
var APP = 'ta-app-' + VERSION;
var PY = 'ta-pyodide-v0.26.4';
var FILES = [
  __FILES__
];
var PYODIDE = [
  __PYODIDE__
];

self.addEventListener('install', function (e) {
  e.waitUntil(
    caches.open(APP).then(function (c) { return c.addAll(FILES); }).then(function () {
      // Python is big (about 12 MB): cache it too, but never fail the install for it
      return caches.open(PY).then(function (c) {
        return Promise.all(PYODIDE.map(function (u) {
          return c.match(u).then(function (hit) { return hit || c.add(u).catch(function () {}); });
        }));
      });
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k !== APP && k !== PY; })
      .map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.href.indexOf('cdn.jsdelivr.net/pyodide/') >= 0) {
    e.respondWith(caches.open(PY).then(function (c) {
      return c.match(req).then(function (hit) {
        return hit || fetch(req).then(function (res) { if (res.ok) c.put(req, res.clone()); return res; });
      });
    }));
    return;
  }
  if (url.origin !== self.location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(function (hit) {
    return hit || fetch(req).then(function (res) {
      if (res.ok) { var copy = res.clone(); caches.open(APP).then(function (c) { c.put(req, copy); }); }
      return res;
    }).catch(function () { return caches.match('./index.html'); });
  }));
});
"""


if __name__ == '__main__':
    if not os.path.exists(os.path.join(SITE, 'icons', 'icon-512.png')):
        make_icons()
    make_sw()
